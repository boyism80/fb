using System.Collections.Generic;
using Fb.Model;
using StackExchange.Redis;

namespace Http.Model
{
    /// <summary>
    /// Represents the Redis hash key for a single storage box entry.
    /// Identifies a record uniquely by user identifier and storage item id.
    /// </summary>
    public class StorageBoxKey : BaseModel, IRedisHashKey
    {
        /// <summary>
        /// Gets or sets the owner user identifier for the storage entry.
        /// </summary>
        /// <value>The character identifier that owns the storage data.</value>
        public required uint User { get; set; }

        /// <summary>
        /// Gets or sets the storage entry identifier that is unique per user.
        /// </summary>
        /// <value>The user-scoped storage entry id generated by the game server.</value>
        public uint Id { get; set; }

        /// <inheritdoc/>
        public uint GetHash() => User;

        /// <inheritdoc/>
        public RedisKey GetRedisKey() => $"cache:storage:box:{User}";

        /// <inheritdoc/>
        public RedisValue GetRedisField() => Id.ToString();
    }

    /// <summary>
    /// Represents a storage box entry that is visible to a single user.
    /// Contains message metadata, attachment payload, and lifecycle information.
    /// </summary>
    public class StorageBox : StorageBoxKey, IModel
    {
        /// <summary>
        /// Gets or sets the title describing the storage entry.
        /// </summary>
        /// <value>A short title shown in the UI.</value>
        public string Title { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the message describing the storage content.
        /// </summary>
        /// <value>A short text shown to the client alongside the attachments.</value>
        public string Message { get; set; } = string.Empty;

        /// <summary>
        /// Gets or sets the attachment payload represented as DSL descriptors.
        /// </summary>
        /// <value>A collection of DSL entries serialized as JSON in the database.</value>
        public List<Dsl> Attachments { get; set; } = new List<Dsl>();

        /// <summary>
        /// Gets or sets a value indicating whether the attachment was received.
        /// </summary>
        /// <value>True if the attachment payload has been consumed; otherwise, false.</value>
        public bool Received { get; set; }

        /// <summary>
        /// Gets or sets the optional expiration timestamp for the storage entry.
        /// </summary>
        /// <value>The date when the entry becomes invalid, or null for permanent items.</value>
        public DateTime? ExpiredDate { get; set; }
    }
}

